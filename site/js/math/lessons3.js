/** Многочлен вида «2x − 3» или «−x + 5» для формулы. */
function lin(a, b, v = 'x') {
  const head = a === 1 ? v : a === -1 ? `-${v}` : `${a}${v}`;
  return b === 0 ? head : `${head} ${sgn(b)}`;
}

/** Квадратный трёхчлен «x^2 − 5x + 6» для формулы. */
function quad(a, b, c) {
  let out = a === 1 ? 'x^2' : a === -1 ? '-x^2' : `${a}x^2`;
  if (b) out += ` ${b < 0 ? '-' : '+'} ${Math.abs(b) === 1 ? '' : Math.abs(b)}x`;
  if (c) out += ` ${sgn(c)}`;
  return out;
}

