const randomList = (n, lo = 1, hi = 60) => {
  const pool = [];
  for (let v = lo; v <= hi; v++) pool.push(v);
  return shuffle(pool).slice(0, n);
};
const sortedList = (n, lo = 1, hi = 60) => randomList(n, lo, hi).sort((a, b) => a - b);

